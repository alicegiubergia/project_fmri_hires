#!/usr/bin/env python3
"""
Group-level analysis of physiological metrics (HRV, RVT, RV)
============================================================

Reads subject-level metrics generated by the physio preprocessing script
and computes group statistics and plots interactive summaries.

Input:  derivatives/physio/sub-XX/func/run-XX/*_HRV.tsv, *_RVT.tsv, *_RV.tsv
Output: derivatives/physio/group_physio_report.html
"""

import os
import glob
import numpy as np
import pandas as pd
import plotly.graph_objects as go
import plotly.io as pio

# ===============================
# CONFIGURATION
# ===============================

DERIV_DIR = "/mnt/store2/projects/progetto_layer/data/derivatives/physio"
MODE = 'orig_raw' # 'orig_convolved', 'resampled_raw'. 'resampled_convolved'
OUTPUT_HTML = os.path.join(DERIV_DIR, f"group_physio_report_{MODE}.html")

metrics = ["HRV", "RVT", "RV"]
subjects = sorted([s for s in os.listdir(DERIV_DIR) if s.startswith("sub-")])

# ===============================
# COLLECT METRICS
# ===============================

group_data = {m: [] for m in metrics}

for subj in subjects:
    func_dir = os.path.join(DERIV_DIR, subj, "func")
    if not os.path.exists(func_dir):
        continue
    for run_dir in sorted(os.listdir(func_dir)):
        run_path = os.path.join(func_dir, run_dir)
        if not os.path.isdir(run_path):
            continue
        for m in metrics:
            files = glob.glob(os.path.join(run_path, f"*_{m}_{MODE}.1D"))
            for f in files:
                try:
                    data = np.loadtxt(f)
                    if data.ndim > 1:
                        data = data[:, 1]  # usa la colonna convoluta (∗ CRF)
                    group_data[m].append({
                        "subject": subj,
                        "run": run_dir,
                        "metric": m,
                        "mean": np.mean(data),
                        "std": np.std(data),
                        "median": np.median(data),
                        "mad": np.median(np.abs(data - np.median(data))),
                    })
                except Exception as e:
                    print(f"⚠️ Error reading {f}: {e}")

# ===============================
# CONVERT TO DATAFRAME
# ===============================

df_metrics = pd.concat([pd.DataFrame(group_data[m]) for m in metrics])
summary = df_metrics.groupby("metric").agg({
    "mean": ["mean", "std"],
    "std": ["mean", "std"],
    "median": ["mean", "std"]
}).round(4)
print("\n=== Group Summary ===")
print(summary)

# ===============================
# PLOTS
# ===============================

figs = []
for m in metrics:
    df = df_metrics[df_metrics["metric"] == m]

    # --- Boxplot per soggetto ---
    fig_box = go.Figure()
    for subj in subjects:
        subj_df = df[df["subject"] == subj]
        if subj_df.empty:
            continue
        fig_box.add_trace(go.Box(
            y=subj_df["mean"],
            name=subj,
            boxpoints='all',
            jitter=0.3,
            pointpos=-1.8
        ))
    fig_box.update_layout(
        title=f"{m} distribution across subjects/runs",
        yaxis_title=f"{m} value",
        template="plotly_white"
    )

    # --- Istogramma gruppale ---
    fig_hist = go.Figure()
    fig_hist.add_trace(go.Histogram(
        x=df["mean"],
        nbinsx=30,
        marker_color="royalblue",
        opacity=0.7,
        name=f"{m} mean"
    ))
    fig_hist.update_layout(
        title=f"Group distribution of {m} (mean values)",
        xaxis_title=f"{m}",
        yaxis_title="Count",
        template="plotly_white"
    )

    figs.append((m, fig_box, fig_hist))

# ===============================
# BUILD HTML REPORT
# ===============================

html_sections = []
for m, fig_box, fig_hist in figs:
    html_box = pio.to_html(fig_box, include_plotlyjs='cdn', full_html=False)
    html_hist = pio.to_html(fig_hist, include_plotlyjs=False, full_html=False)
    html_sections.append(f"""
    <h2>{m}</h2>
    <p>Distribuzione di <b>{m}</b> per soggetto e run, con statistiche di gruppo.</p>
    {html_box}
    {html_hist}
    """)

final_html = f"""
<html>
<head>
<meta charset="utf-8">
<title>Group Physiological Report</title>
<style>
body {{
    font-family: "Segoe UI", sans-serif;
    margin: 40px;
}}
h1 {{
    color: #1a1a1a;
}}
h2 {{
    color: #2c3e50;
    border-bottom: 2px solid #eee;
    padding-bottom: 5px;
    margin-top: 50px;
}}
p {{
    color: #555;
    margin-bottom: 15px;
}}
</style>
</head>
<body>
<h1>Group Physiological Report "{MODE}"</h1>
<p>Analisi di gruppo delle metriche HRV, RVT, RV su tutti i soggetti.</p>
{''.join(html_sections)}
<h3>Group Summary Table</h3>
<pre>{summary.to_string()}</pre>
</body>
</html>
"""

with open(OUTPUT_HTML, "w", encoding="utf-8") as f:
    f.write(final_html)

print(f"\n✅ Group report saved: {OUTPUT_HTML}")
